// Design-to-motion, target A: compile a normalized scene into a standalone
// HyperFrames project (index.html + vendored GSAP + copied assets).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { EASES, IDENTITY } from '../shared/motion.js';
import { boxStyle, contentStyle, imageStyle, toCss } from '../shared/layer-style.js';
import { textGroups } from './normalize.js';

const require = createRequire(import.meta.url);
const n = (v) => Number(v.toFixed(3));

/**
 * @param scene     output of normalizeDesign()
 * @param outDir    project directory to (re)create
 * @param opts.baseDir     directory image `src` paths are relative to
 * @param opts.transparent render over a transparent background (for overlays)
 */
export function compileToHyperFrames(scene, outDir, { baseDir = process.cwd(), transparent = false } = {}) {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(path.join(outDir, 'assets'), { recursive: true });
  fs.copyFileSync(require.resolve('gsap/dist/gsap.min.js'), path.join(outDir, 'assets', 'gsap.min.js'));

  const tweens = [];
  const assetFor = (src) => {
    const abs = path.resolve(baseDir, src);
    if (!fs.existsSync(abs)) throw new Error(`Image not found: ${abs}`);
    const name = `${tweens.length}-${path.basename(abs)}`.replace(/[^a-zA-Z0-9._-]/g, '_');
    fs.copyFileSync(abs, path.join(outDir, 'assets', name));
    return `assets/${name}`;
  };

  const renderLayer = (l) => {
    const sel = `#${l.id}`;
    const m = l.motion;
    let inner = '';
    if (l.type === 'text') {
      if (m.split) {
        let i = 0;
        inner = textGroups(l.text, m.split)
          .map((g) => {
            if (g.space != null) return escapeHtml(g.space);
            const spans = g.pieces.map((piece) => {
              const pid = `${l.id}-p${i}`;
              tweens.push(entrance(`#${pid}`, m, i * m.stagger));
              i++;
              return `<span id="${pid}" style="display:inline-block">${escapeHtml(piece)}</span>`;
            }).join('');
            return g.pieces.length > 1 ? `<span style="display:inline-block;white-space:nowrap">${spans}</span>` : spans;
          })
          .join('');
      } else inner = escapeHtml(l.text);
    } else if (l.type === 'image') {
      inner = `<img src="${assetFor(l.src)}" alt="" style="${toCss(imageStyle(l))}">`;
    } else if (l.type === 'group') {
      inner = l.children.map(renderLayer).join('\n');
    }
    if (!(l.type === 'text' && m.split)) tweens.push(entrance(sel, m, 0));
    if (m.idle) tweens.push(idle(`#${l.id}-idle`, m, scene.duration));
    if (m.exit.duration > 0) tweens.push(exitTween(sel, m, scene.duration));

    return `<div id="${l.id}" style="${toCss(boxStyle(l))}"><div id="${l.id}-idle" style="position:absolute;inset:0"><div style="${toCss(contentStyle(l))}">${inner}</div></div></div>`;
  };

  const body = scene.layers.map(renderLayer).join('\n    ');
  const bg = transparent ? 'transparent' : scene.background;

  const comment = `<!-- Generated by video-studio design-to-motion from "${escapeHtml(scene.name)}" (style: ${scene.style}). -->`;
  // index.html mounts one scene file, the layout HyperFrames' Studio/desktop app edits best.
  const index = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${scene.width}, height=${scene.height}" />
    ${comment}
    <script src="assets/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: ${scene.width}px; height: ${scene.height}px; overflow: hidden; background: ${bg}; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${scene.duration}" data-fps="${scene.fps}" data-width="${scene.width}" data-height="${scene.height}">
      <div id="scene" data-composition-id="scene" data-composition-src="compositions/scene.html" data-start="0" data-duration="${scene.duration}" data-track-index="0" data-track-kind="graphics" data-width="${scene.width}" data-height="${scene.height}"></div>
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
  const sceneHtml = `${comment}
<template>
  <style>
    #root { position: absolute; inset: 0; overflow: hidden; background: ${bg}; font-family: 'Inter', sans-serif; }
  </style>
  <div id="root" data-composition-id="scene" data-width="${scene.width}" data-height="${scene.height}" data-layout-allow-overflow data-layout-allow-overlap>
    ${body}
  </div>
  <script>
    const tl = gsap.timeline({ paused: true });
    ${tweens.filter(Boolean).join('\n    ')}
    window.__timelines["scene"] = tl;
  </script>
</template>
`;
  fs.mkdirSync(path.join(outDir, 'compositions'), { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), index);
  fs.writeFileSync(path.join(outDir, 'compositions', 'scene.html'), sceneHtml);
  fs.writeFileSync(path.join(outDir, 'hyperframes.json'), JSON.stringify({ paths: { blocks: 'compositions', components: 'compositions/components', assets: 'assets' } }, null, 2));
  return path.join(outDir, 'index.html');
}

function gsapVars(state, keys) {
  const v = {};
  for (const k of keys) {
    if (k === 'blur') v.filter = `blur(${n(state.blur)}px)`;
    else if (k === 'clip') v.clipPath = `inset(0% ${n((1 - state.clip) * 100)}% 0% 0%)`;
    else if (k === 'rotation') v.rotation = n(state.rotation);
    else v[k] = n(state[k]);
  }
  return v;
}

function entrance(sel, m, extraDelay) {
  if (m.duration <= 0) return '';
  const keys = Object.keys(IDENTITY).filter((k) => m.from[k] !== IDENTITY[k]);
  if (!keys.length) return '';
  const from = gsapVars(m.from, keys);
  const to = { ...gsapVars(IDENTITY, keys), duration: n(m.duration), ease: EASES[m.ease].gsap };
  return `tl.fromTo(${JSON.stringify(sel)}, ${JSON.stringify(from)}, ${JSON.stringify(to)}, ${n(m.delay + extraDelay)});`;
}

function exitTween(sel, m, sceneDuration) {
  const keys = Object.keys(IDENTITY).filter((k) => m.exit.to[k] !== IDENTITY[k]);
  if (!keys.length) return '';
  const from = gsapVars(IDENTITY, keys);
  const to = { ...gsapVars(m.exit.to, keys), duration: n(m.exit.duration), ease: EASES[m.exit.ease].gsap, immediateRender: false };
  return `tl.fromTo(${JSON.stringify(sel)}, ${JSON.stringify(from)}, ${JSON.stringify(to)}, ${n(sceneDuration - m.exit.duration)});`;
}

// A sine wave expressed as a custom ease, so it is a pure function of timeline time.
function idle(sel, m, sceneDuration) {
  const { prop, amplitude, period } = m.idle;
  const len = Math.max(0.01, sceneDuration - m.delay);
  const cycles = n(len / period);
  return `tl.to(${JSON.stringify(sel)}, { ${prop}: ${prop === 'scale' ? 1 + amplitude : amplitude}, duration: ${n(len)}, ease: (p) => Math.sin(p * ${cycles} * Math.PI * 2), immediateRender: false }, ${n(m.delay)});`;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
}
